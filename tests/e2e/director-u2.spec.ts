import { test, expect } from '@playwright/test'

for (const theme of ['dark', 'light']) for (const width of [1440]) {
  test(`U2 mode controls retain drafts ${theme} ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 960 })
    await page.emulateMedia({ reducedMotion: 'reduce', colorScheme: theme as 'dark' | 'light' })
    await page.addInitScript(theme => localStorage.setItem('aics_theme', theme), theme)
    await page.goto('/prompt-builder')
    await expect(page.locator('.gen-bar')).toBeVisible()
    const randomMenu = page.locator('.random-menu-trigger')
    await expect(randomMenu).toBeVisible()
    await expect(randomMenu).toBeEnabled()
    await randomMenu.click()
    const randomUndo = page.locator('.random-undo')
    await expect(randomUndo).toBeDisabled()
    await expect(randomUndo).toHaveCSS('opacity', '1')
    await expect(randomUndo).toHaveCSS('color', await randomUndo.evaluate(el => {
      const probe = document.createElement('span')
      probe.style.color = 'var(--text-disabled)'; el.append(probe)
      const color = getComputedStyle(probe).color; probe.remove(); return color
    }))
    await randomMenu.click()

    await expect(page.locator('.utility-trigger')).toHaveAccessibleName(/尚未备份/)
    await page.locator('[aria-controls="material-scenes"]').click()
    await page.locator('.scene-search').fill('樱花')
    await page.locator('[aria-controls="material-story"]').click()
    const story = page.locator('.story-input')
    await story.fill('审核用草稿：窗外下着雨。')
    await page.getByRole('button', { name: '专家模式', exact: true }).click()
    await expect(story).toHaveValue('审核用草稿：窗外下着雨。')
    await page.locator('.engine-btn').filter({ hasText: 'SD 引擎' }).click()
    await page.getByLabel('相关性 (CFG)', { exact: true }).fill('6.5')
    await page.getByLabel('相关性 (CFG)', { exact: true }).press('Tab')
    await expect(page.locator('.toast-item')).toHaveCount(0)
    await page.locator('.director-inspector').screenshot({ path: info.outputPath(`sd-notebook-${theme}-${width}.png`) })
    await page.getByRole('button', { name: '场景模式', exact: true }).click()
    await expect(story).toHaveValue('审核用草稿：窗外下着雨。')
    await page.locator('[aria-controls="material-scenes"]').click()
    await expect(page.locator('.scene-search')).toHaveValue('樱花')
    await page.getByRole('button', { name: '专家模式', exact: true }).click()
    // 场景模式沿用自动路线；返回 SD 后检查该引擎的草稿，而非假设路线不切换。
    await page.locator('.engine-btn').filter({ hasText: 'SD 引擎' }).click()
    await expect(page.getByLabel('相关性 (CFG)', { exact: true })).toHaveValue('6.5')

    await page.locator('[aria-controls="material-character"]').click()
    await page.getByRole('button', { name: /热门角色/ }).first().click()
    const subject = await page.locator('.pb').getAttribute('data-character')
    const outfit = await page.locator('.outfit-chip.active').textContent()
    const disabledEngine = page.locator('.engine-btn').first()
    await expect(disabledEngine).toBeDisabled()
    await expect(disabledEngine).toHaveCSS('opacity', '1')
    await expect(page.locator('.toast-item')).toHaveCount(0)
    await page.locator('.director-inspector').screenshot({ path: info.outputPath(`anima-notebook-${theme}-${width}.png`) })
    await expect(disabledEngine).toHaveCSS('color', await disabledEngine.evaluate(el => {
      const probe = document.createElement('span')
      probe.style.color = 'var(--text-disabled)'; el.append(probe)
      const color = getComputedStyle(probe).color; probe.remove(); return color
    }))
    await page.getByRole('button', { name: '场景模式', exact: true }).click()
    await page.getByRole('button', { name: '专家模式', exact: true }).click()
    await expect(page.locator('.pb')).toHaveAttribute('data-character', subject!)
    await expect(page.locator('.outfit-chip.active')).toHaveText(outfit!)
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
    await page.screenshot({ path: info.outputPath(`${theme}-${width}-u2.png`), fullPage: true })
  })
}

test('selected scene survives an expert-mode round trip', async ({ page }) => {
  await page.goto('/prompt-builder?scene=sc006')
  const studio = page.locator('article.pb')
  const context = page.locator('.atelier-context')
  const basicMode = page.getByRole('button', { name: '场景模式', exact: true })
  const expertMode = page.getByRole('button', { name: '专家模式', exact: true })
  await basicMode.click()
  await expect(studio).toHaveAttribute('data-director-mode', 'basic')
  await expect(studio).toHaveAttribute('data-character', 'nene')
  await expect(context).toContainText('平安夜的手作礼物')
  const sceneContext = await context.innerText()

  await expertMode.click()
  await expect(studio).toHaveAttribute('data-director-mode', 'pro')
  await expect(studio).toHaveAttribute('data-character', 'nene')
  await expect(context).toHaveText(sceneContext)
  await basicMode.click()
  await expect(studio).toHaveAttribute('data-director-mode', 'basic')
  await expect(studio).toHaveAttribute('data-character', 'nene')
  await expect(context).toHaveText(sceneContext)
})

for (const theme of ['dark', 'light']) {
  test(`single description editor and Terraria workspace ${theme}`, async ({ page }, info) => {
    test.setTimeout(60000)
    await page.setViewportSize({ width: 1440, height: 960 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.addInitScript(theme => {
      localStorage.setItem('aics_guest_guide_dismissed', '1')
      localStorage.setItem('atelier-desktop-appearance-v1', JSON.stringify({ theme, style: 'terraria', motion: 'reduce' }))
    }, theme)
    await page.goto('/prompt-builder?scene=sc006')
    await expect(page.locator('html')).toHaveAttribute('data-theme-style', 'terraria')
    await expect(page.locator('[aria-controls="material-scenes"]')).toHaveAttribute('aria-pressed', 'true')
    const shortcut = page.getByRole('button', { name: '编辑画面描述', exact: true })
    const description = page.locator('#visualDescription')
    await expect(shortcut).toHaveCount(1)
    await shortcut.focus()
    await shortcut.press('Enter')
    await expect(description).toBeFocused()
    await description.fill('窗边的女孩抬起手，柔和的晨光照亮白色衣袖。')
    await expect(page.locator('#inspectorVisualDescription')).toHaveCount(0)
    const expectedDescription = await description.inputValue()
    await page.getByRole('button', { name: '专家模式', exact: true }).click()
    await expect(description).toHaveValue(expectedDescription)

    const materials = page.locator('#drawing-materials')
    const inspector = page.locator('#drawing-inspector')
    const nav = page.getByRole('navigation', { name: '主导航', exact: true })
    const links = nav.locator('.nav-links > a')
    for (const width of [1440, 1280]) {
      await page.setViewportSize({ width, height: 960 })
      await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
      const materialBox = (await materials.boundingBox())!
      const canvasBox = (await page.locator('#drawing-canvas').boundingBox())!
      const inspectorBox = (await inspector.boundingBox())!
      expect(materialBox.x + materialBox.width).toBeLessThanOrEqual(canvasBox.x)
      expect(canvasBox.width).toBeGreaterThanOrEqual(320)
      expect(canvasBox.x + canvasBox.width).toBeLessThanOrEqual(inspectorBox.x)
      expect(inspectorBox.y + inspectorBox.height).toBeLessThanOrEqual(960)
      const navBox = (await nav.boundingBox())!
      if (width === 1440) expect(navBox.x + navBox.width).toBeLessThan(materialBox.x)
      else expect(navBox.y + navBox.height).toBeLessThanOrEqual(materialBox.y)
      await links.first().focus()
      await links.first().press(width === 1440 ? 'ArrowDown' : 'ArrowRight')
      await expect(links.nth(1)).toBeFocused()
      await page.screenshot({ path: info.outputPath(`terraria-description-${theme}-${width}.png`) })
    }

    const materialHandle = page.getByRole('separator', { name: '调整素材栏宽度' })
    await materialHandle.focus()
    await materialHandle.press('ArrowRight')
    const chosenWidth = await materialHandle.getAttribute('aria-valuenow')
    await page.getByRole('button', { name: '工作台布局', exact: true }).click()
    await page.getByRole('button', { name: '收起素材', exact: true }).click()
    await page.keyboard.press('Escape')
    await expect(shortcut).toHaveCount(1)
    await shortcut.click()
    await expect(description).toBeFocused()
    await expect(inspector).toBeVisible()
    await expect(materialHandle).toHaveAttribute('aria-valuenow', chosenWidth!)

    // Hiding both rails leaves exactly one entry; it restores only the editor's rail.
    await page.getByRole('button', { name: '工作台布局', exact: true }).click()
    await page.getByRole('button', { name: '收起素材', exact: true }).click()
    await page.getByRole('button', { name: '收起参数', exact: true }).click()
    await page.keyboard.press('Escape')
    await expect(materials).toBeHidden()
    await expect(inspector).toBeHidden()
    await expect(shortcut).toHaveCount(1)
    await shortcut.click()
    await expect(description).toBeFocused()
    await expect(description).toHaveValue(expectedDescription)
    await expect(inspector).toBeHidden()
    await expect(materialHandle).toHaveAttribute('aria-valuenow', chosenWidth!)
    await page.getByRole('button', { name: '进入专注成片模式', exact: true }).click()
    await shortcut.click()
    await expect(description).toBeFocused()
    await expect(page.locator('.pb')).not.toHaveClass(/focus-mode/)
    await expect(inspector).toBeHidden()

    // Narrow windows show the same editor without reviving the removed right input.
    await page.setViewportSize({ width: 900, height: 900 })
    await page.locator('[aria-controls="material-scenes"]').click()
    await expect(shortcut).toHaveCount(1)
    await shortcut.focus()
    await shortcut.press('Enter')
    await expect(description).toBeFocused()
    await expect(description).toBeInViewport({ ratio: 1 })
    await expect(description).toHaveValue(expectedDescription)
    await expect(page.locator('#inspectorVisualDescription')).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
    await page.screenshot({ path: info.outputPath(`terraria-description-${theme}-900.png`) })
  })
}
